-- Server transactions must reject global-versus-branch promotion collisions.

-- Aggregate values below are views, not stored attributes in the 3NF core.

CREATE VIEW quote_totals AS
WITH lines AS (
 SELECT quote_id, SUM(unit_price + express_fee) AS subtotal
 FROM quote_items GROUP BY quote_id
), amounts AS (
 SELECT q.id AS quote_id, q.order_id, COALESCE(l.subtotal,0) AS subtotal,
 CASE WHEN q.kind = 'LOGISTICS' THEN 0
      ELSE LEAST(COALESCE(p.cap_amount,0),
          ROUND(COALESCE(l.subtotal,0) * COALESCE(p.percent,0)::numeric / 100)) END AS discount,
 CASE WHEN o.fulfilment_mode = 'BOTH' THEN
     CEIL(GREATEST(COALESCE(o.distance_km,0) - s.free_km,0)) * s.rate_per_km
     ELSE 0 END AS pickup_fee
 FROM price_quotes q JOIN orders o ON o.id = q.order_id
 JOIN shipping_policy_versions s ON s.id = o.shipping_policy_version_id
 LEFT JOIN promotion_versions p ON p.id = o.promotion_version_id
 LEFT JOIN lines l ON l.quote_id = q.id
)
SELECT *, subtotal - discount + pickup_fee AS total FROM amounts;

CREATE VIEW verified_sales AS
SELECT v.order_id, s.id AS submission_id, s.reviewed_at AS verified_at, t.total
FROM verified_payments v JOIN payment_submissions s ON s.id = v.submission_id
JOIN quote_totals t ON t.quote_id = s.quote_id
WHERE s.decision = 'VERIFIED';
